'use strict';
// The page's languages. The English text is the key: t('Saved {time}', {time}) gives the
// translation of the current language, or the English when there's none. To add a language,
// copy the `es` block, translate its values (keep the {words} in braces), and list it in LANGUAGES.

const LANGUAGES = {en: 'English', es: 'Español'};

const I18N = {lang: 'en'};

function t(text, vars) {
	const table = I18N[I18N.lang];
	let out = (table && table[text]) || text;
	if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
	return out;
}

function setLanguage(lang) {
	I18N.lang = LANGUAGES[lang] ? lang : 'en';
	try { localStorage.setItem('dialogos.ui', I18N.lang); } catch (e) { /* (only a preference) */ }
}

function initLanguage() {
	let saved = null;
	try { saved = localStorage.getItem('dialogos.ui'); } catch (e) { /* (private window) */ }
	const asked = new URLSearchParams(location.search).get('lang');
	const browser = (navigator.language || 'en').slice(0, 2).toLowerCase();
	I18N.lang = [asked, saved, browser].find(l => l && LANGUAGES[l]) || 'en';
}

